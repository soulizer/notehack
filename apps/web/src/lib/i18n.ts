export type Translate = (zh: string, vars?: Record<string, string | number>) => string;

export function translate(zh: string, vars?: Record<string, string | number>): string {
  let output = currentLocale === 'en' ? en[zh] ?? zh : zh;
  if (vars) {
    for (const [key, value] of Object.entries(vars)) {
      output = output.replaceAll(`{${key}}`, String(value));
    }
  }
  return output;
}

export function useT(): Translate {
  const locale = useSyncExternalStore(subscribe, getLocale, getLocale);
  void locale;
  return translate;
}

export function formatNumber(value: number, locale: Locale = currentLocale): string {
  return new Intl.NumberFormat(locale === 'en' ? 'en-US' : 'zh-CN').format(value);
}

