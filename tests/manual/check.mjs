import { chromium } from '@playwright/test';
import { EMAIL, PASSWORD } from './config.mjs';
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 980 }, deviceScaleFactor: 1 });
const page = await context.newPage();
const errors=[];
page.on('console', msg=>{ if(msg.type()==='error') errors.push('CONSOLE: '+msg.text()); });
page.on('pageerror', err=>errors.push('PAGEERROR: '+err.message));
await page.goto('http://127.0.0.1:8787/login', { waitUntil: 'networkidle' });
await page.screenshot({ path: '/tmp/login.png', fullPage: true });
await page.fill('#login-email',EMAIL);
await page.fill('#login-password',PASSWORD);
await page.click('button[type=submit]');
await page.waitForTimeout(3500);
console.log('url', page.url());
await page.screenshot({ path: '/tmp/app.png', fullPage: true });
console.log('errors', errors.slice(0,20));
console.log('title', await page.title());
const text = await page.locator('body').innerText();
console.log(text.slice(0,1200));
await browser.close();
