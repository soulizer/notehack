import { chromium } from '@playwright/test';
import { EMAIL, PASSWORD } from './config.mjs';
const browser = await chromium.launch({headless:true});
const ctx = await browser.newContext({viewport:{width:1440,height:980},locale:'zh-CN'});
await ctx.addInitScript(()=>localStorage.setItem('nh-locale','zh-CN'));
const page = await ctx.newPage();
const errs=[]; page.on('pageerror',e=>errs.push('PAGE:'+e.message)); page.on('console',m=>{if(m.type()==='error'&&!m.text().includes('401'))errs.push('CONSOLE:'+m.text())});
await page.goto('http://127.0.0.1:8787/login',{waitUntil:'networkidle'});
await page.fill('#login-email',EMAIL); await page.fill('#login-password',PASSWORD); await page.click('button[type=submit]'); await page.waitForTimeout(1500);
await page.goto('http://127.0.0.1:8787/app/settings/data?import=1',{waitUntil:'networkidle'}); await page.waitForTimeout(800);
console.log('modal open', await page.locator('.modal').count());
const fileInput = page.locator('.modal input[type=file]');
await fileInput.setInputFiles('/tmp/import-sample.zip');
await page.click('text=开始导入');
await page.waitForTimeout(3000);
await page.screenshot({path:'/tmp/import-preview.png',fullPage:true});
console.log('preview text', (await page.locator('.modal').innerText()).slice(0,700));
await page.click('text=执行导入');
await page.waitForTimeout(6000);
await page.screenshot({path:'/tmp/import-done.png',fullPage:true});
console.log('done text', (await page.locator('.modal').innerText()).slice(0,500));
console.log('errors',errs.slice(0,15));
await browser.close();
