import { chromium } from '@playwright/test';
import { EMAIL, PASSWORD } from './config.mjs';
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 980 }, deviceScaleFactor: 1, locale: 'zh-CN' });
await context.addInitScript(() => localStorage.setItem('nh-locale','zh-CN'));
const page = await context.newPage();
const errors=[];
page.on('console', msg=>{ if(msg.type()==='error') errors.push('CONSOLE: '+msg.text()); });
page.on('pageerror', err=>errors.push('PAGEERROR: '+err.message));
await page.goto('http://127.0.0.1:8787/', { waitUntil: 'networkidle' });
await page.screenshot({ path: '/tmp/landing.png', fullPage: true });
await page.goto('http://127.0.0.1:8787/login', { waitUntil: 'networkidle' });
await page.screenshot({ path: '/tmp/login-zh.png', fullPage: true });
await page.fill('#login-email',EMAIL);
await page.fill('#login-password',PASSWORD);
await page.click('button[type=submit]');
await page.waitForTimeout(2500);
await page.click('.note-item');
await page.waitForTimeout(1800);
await page.screenshot({ path: '/tmp/editor.png', fullPage: true });
console.log('url', page.url());
console.log('errors', errors.slice(0,15));
console.log('editor text', (await page.locator('.editor-page').innerText()).slice(0,500));
await page.goto('http://127.0.0.1:8787/app/settings/security', { waitUntil: 'networkidle' });
await page.waitForTimeout(1000);
await page.screenshot({ path: '/tmp/settings.png', fullPage: true });
console.log('settings text', (await page.locator('.settings-inner').innerText()).slice(0,500));
await browser.close();
